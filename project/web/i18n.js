/** @returns {Locale} */
export function getLocale() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && Object.hasOwn(MESSAGES, saved)) return /** @type {Locale} */ (saved);
  } catch {
    return "en";
  }
  return "en";
}

/** @param {Locale} locale */
export function setLocale(locale) {
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // The current page can still use the selected locale without storage access.
  }
  document.documentElement.lang = LANGUAGES.find(([code]) => code === locale)?.[2] ?? "en";
}

/** @param {string} message */
/** @param {string} message @param {Readonly<Record<string, string | number>>} [values] */
export function t(message, values = {}) {
  const translated = ADDITIONAL_MESSAGES[getLocale()][message] ?? MESSAGES[getLocale()][message] ?? message;
  return translated.replace(/\{(\w+)\}/g, (placeholder, key) => String(values[key] ?? placeholder));
}

export function localeTag() {
  return LANGUAGES.find(([code]) => code === getLocale())?.[2] ?? "en-US";
}

/** @param {string} locale */
export function isLocale(locale) {
  return Object.hasOwn(MESSAGES, locale);
}
